#!/usr/bin/env python3
"""Compile a guest ACPI DDC control using the original panel EDID."""
import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

ACPI_ID = 0x8000A450


def asl_buffer(data: bytes, name: str = "EDID") -> str:
    lines = [f"        Name ({name}, Buffer (0x{len(data):03X})", "        {"]
    for off in range(0, len(data), 16):
        chunk = data[off:off + 16]
        hexpart = ", ".join(f"0x{b:02X}" for b in chunk)
        lines.append(f"            /* {off:04X} */  {hexpart},")
    if lines[-1].endswith(","):
        lines[-1] = lines[-1][:-1]
    lines.append("        })")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("edid")
    ap.add_argument("--out-prefix", default=os.path.join(HERE, "SSDT-ddc-control"))
    args = ap.parse_args()

    path = args.edid
    with open(path, "rb") as edid_file:
        edid = edid_file.read()
    if len(edid) not in (128, 256, 384, 512) or not edid.startswith(bytes.fromhex("00 ff ff ff ff ff ff 00")):
        ap.error("invalid EDID header or length")
    if edid[126] != len(edid) // 128 - 1:
        ap.error("EDID extension count does not match its length")
    if any(sum(edid[i:i + 128]) % 256 for i in range(0, len(edid), 128)):
        ap.error("EDID checksum mismatch")
    edid_buffers = "\n".join(
        asl_buffer(edid[:size], f"ED{size // 128:02}") for size in range(128, len(edid) + 1, 128)
    )
    edid_returns = "\n".join(
        f"                If (Arg0 == {count}) {{ Return (ED{count:02}) }}"
        for count in range(1, len(edid) // 128 + 1)
    )

    dsl = f"""/*
 * Guest ACPI _DOD/_DDC EDID override.
 * Generated by make-ddc-ssdt.py.
 * Guest DDC consumption must be established with the existing trace.
 */
DefinitionBlock ("", "SSDT", 2, "LNVVM", "DDCEDID", 0x00000001)
{{
    External (_SB_.PCI0.S15_.S00_, DeviceObj)
    External (_SB_.VHEX, MethodObj)
    External (_SB_.VOUT, FieldUnitObj)

    Scope (\\_SB.PCI0.S15.S00)
    {{
{edid_buffers}

        Method (_DOD, 0, NotSerialized)  // _DOD: Display Output Devices
        {{
            Return (Package (0x01)
            {{
                0x{ACPI_ID:08X}
            }})
        }}

        Device (LCD0)
        {{
            Method (_ADR, 0, Serialized)  // _ADR: Address
            {{
                Return (0x{ACPI_ID:08X})
            }}

            Method (_DDC, 1, Serialized)  // _DDC: Display Data Current
            {{
                \\_SB.VOUT = 0x45
                \\_SB.VHEX (Arg0)
                \\_SB.VOUT = 0x0A
{edid_returns}
                Return (Zero)
            }}
        }}
    }}
}}
"""
    dsl_path = args.out_prefix + ".dsl"
    aml_path = args.out_prefix + ".aml"
    edid_path = args.out_prefix + ".edid.bin"
    with open(dsl_path, "w") as f:
        f.write(dsl)
    with open(edid_path, "wb") as f:
        f.write(edid)
    print("wrote", dsl_path)
    print("wrote", edid_path)

    subprocess.run(["iasl", "-p", args.out_prefix, dsl_path], check=True)
    print("wrote", aml_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
